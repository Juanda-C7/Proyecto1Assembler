; Busca todas las apariciones de SEARCH_WORD en TEXT_BUFFER y las
; reemplaza por REPLACE_WORD (rellena con espacios si es mas corta,
; la recorta si es mas larga, para no mover el resto del texto)

DOREPLACE PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI

    CMP SEARCH_LEN,00H
    JE DR_DONE

    MOV SI,0000H

DR_OUTER:

    MOV AX,SI
    XOR CH,CH
    MOV CL,SEARCH_LEN
    ADD AX,CX

    CMP AX,1840
    JA DR_DONE

    XOR BX,BX

DR_CMP:

    CMP BL,SEARCH_LEN
    JAE DR_MATCH

    LEA DI,TEXT_BUFFER
    ADD DI,SI
    ADD DI,BX
    MOV AL,[DI]

    LEA DI,SEARCH_WORD
    ADD DI,BX
    MOV AH,[DI]

    CMP AL,AH
    JNE DR_NOMATCH

    INC BX
    JMP DR_CMP

DR_MATCH:

    XOR BX,BX

DR_WRITE:

    CMP BL,SEARCH_LEN
    JAE DR_ADVANCE

    CMP BL,REPLACE_LEN
    JAE DR_WRITE_SPACE

    LEA DI,REPLACE_WORD
    ADD DI,BX
    MOV AL,[DI]

    JMP DR_WRITE_CHAR

DR_WRITE_SPACE:

    MOV AL,' '

DR_WRITE_CHAR:

    LEA DI,TEXT_BUFFER
    ADD DI,SI
    ADD DI,BX
    MOV [DI],AL

    LEA DI,ATTR_BUFFER
    ADD DI,SI
    ADD DI,BX
    MOV DL,EDITOR_ATTRIB
    MOV [DI],DL

    INC BX
    JMP DR_WRITE

DR_ADVANCE:

    MOV AX,SI
    XOR CH,CH
    MOV CL,SEARCH_LEN
    ADD AX,CX
    MOV SI,AX

    JMP DR_OUTER

DR_NOMATCH:

    INC SI
    JMP DR_OUTER

DR_DONE:

    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX

    RET

DOREPLACE ENDP

; Pide palabra a buscar y palabra de reemplazo, y hace el reemplazo (ALT+B)
; Cancelar con ALT+Z/ALT+X en cualquiera de los dos pasos no cambia nada

