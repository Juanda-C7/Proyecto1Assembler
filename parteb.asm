; Muestra la pantalla para pedir el nombre del archivo a abrir

SHOWOPEN PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH BP

    CALL Q10CLEAR

    MOV BP,OFFSET OPEN_TITLE
    MOV CX,OPEN_TITLE_LEN
    MOV DH,05
    MOV DL,22
    MOV BL,1EH
    CALL PRINT_AT

    MOV BP,OFFSET OPEN_PROMPT
    MOV CX,OPEN_PROMPT_LEN
    MOV DH,08
    MOV DL,24
    MOV BL,1FH
    CALL PRINT_AT

    MOV BP,OFFSET OPEN_EXTENSION
    MOV CX,OPEN_EXTENSION_LEN
    MOV DH,11
    MOV DL,16
    MOV BL,1FH
    CALL PRINT_AT

    MOV AH,02H
    MOV BH,00H
    MOV DH,09
    MOV DL,22

    INT 10H

    POP BP
    POP DX
    POP CX
    POP BX
    POP AX

    RET

SHOWOPEN ENDP

; Carga el contenido del archivo ya abierto dentro del buffer del editor

LOADTEXT PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX

    CALL EDITOR_INIT

    MOV BX,FILE_HANDLE

    MOV AH,3FH
    MOV CX,1840

    LEA DX,TEXT_BUFFER

    INT 21H

    MOV BX,FILE_HANDLE

    MOV AH,3FH
    MOV CX,1840

    LEA DX,ATTR_BUFFER

    INT 21H

    POP DX
    POP CX
    POP BX
    POP AX

    RET

LOADTEXT ENDP

; Pide el nombre, valida, abre el archivo existente y carga su contenido
; AL=0FFH cancelado, AL=00H exito, AL=01H error (revisar OPEN_ERROR_CODE)

PUBLIC OPENFILE

OPENFILE PROC NEAR

    CALL SHOWOPEN
    CALL GET_FILENAME_INPUT

    CMP AL,0FFH
    JNE OF_CHECK_EMPTY
    RET

OF_CHECK_EMPTY:

    CMP BYTE PTR INPUT_NAME+1,00H
    JNE OF_CHECK_LENGTH
    JMP OF_EMPTY_ERROR

OF_EMPTY_ERROR:

    MOV OPEN_ERROR_CODE,01H
    MOV AL,01H
    RET

OF_CHECK_LENGTH:

    CMP BYTE PTR INPUT_NAME+1,08H
    JBE OF_CHECK_CHARS
    JMP OF_LONG_ERROR

OF_LONG_ERROR:

    MOV OPEN_ERROR_CODE,02H
    MOV AL,01H
    RET

OF_CHECK_CHARS:

    CALL PROCESS_NAME

    CMP AL,00H
    JE OF_BUILD_NAME
    JMP OF_CHAR_ERROR

OF_CHAR_ERROR:

    MOV OPEN_ERROR_CODE,03H
    MOV AL,01H
    RET

OF_BUILD_NAME:

    CALL BUILD_FILENAME

    LEA DX,FILE_NAME
    MOV AL,02H
    MOV AH,3DH

    INT 21H

    JNC OF_SUCCESS
    JMP OF_DOS_ERROR

OF_SUCCESS:

    MOV FILE_HANDLE,AX
    CALL LOADTEXT
    MOV AL,00H
    RET

OF_DOS_ERROR:

    CMP AX,0002H
    JNE OF_ERROR_PATH
    JMP OF_NOTFOUND_ERROR

OF_NOTFOUND_ERROR:

    MOV OPEN_ERROR_CODE,04H
    MOV AL,01H
    RET

OF_ERROR_PATH:

    CMP AX,0003H
    JNE OF_ERROR_ACCESS
    JMP OF_PATH_ERROR

OF_PATH_ERROR:

    MOV OPEN_ERROR_CODE,05H
    MOV AL,01H
    RET

OF_ERROR_ACCESS:

    CMP AX,0005H
    JNE OF_ERROR_FILES
    JMP OF_ACCESS_ERROR

OF_ACCESS_ERROR:

    MOV OPEN_ERROR_CODE,06H
    MOV AL,01H
    RET

OF_ERROR_FILES:

    CMP AX,0004H
    JNE OF_ERROR_OTHER
    JMP OF_FILES_ERROR

OF_FILES_ERROR:

    MOV OPEN_ERROR_CODE,07H
    MOV AL,01H
    RET

OF_ERROR_OTHER:

    MOV OPEN_ERROR_CODE,08H
    MOV AL,01H
    RET

OPENFILE ENDP

