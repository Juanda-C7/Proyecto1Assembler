; Copia lo escrito en INPUT_NAME hacia SEARCH_WORD/SEARCH_LEN

COPYSEARCH PROC NEAR

    PUSH AX
    PUSH CX
    PUSH SI
    PUSH DI

    MOV AL,BYTE PTR INPUT_NAME+1
    MOV SEARCH_LEN,AL

    XOR CX,CX
    MOV CL,AL

    LEA SI,INPUT_NAME+2
    LEA DI,SEARCH_WORD

CS_LOOP:

    CMP CX,0000H
    JE CS_DONE

    MOV AL,[SI]
    MOV [DI],AL

    INC SI
    INC DI
    DEC CX

    JMP CS_LOOP

CS_DONE:

    POP DI
    POP SI
    POP CX
    POP AX

    RET

COPYSEARCH ENDP

