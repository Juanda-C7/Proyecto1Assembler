    CALL RESTORE_IMAGE2_PIXEL

    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX

    RET

CLEAR_CHAR ENDP

; Registra la posicion de una imagen 2 colocada

G20ADD2 PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DI

    MOV BX,PLACEDCOUNT2
    CMP BX,MAXPLACED2
    JB G20_SPACE_OK

    JMP G20_END

G20_SPACE_OK:

    MOV AX,BX
    MOV CX,3
    MUL CX

    MOV DI,OFFSET PLACED2
    ADD DI,AX

    MOV BYTE PTR [DI],01H

    MOV AL,EDITOR_ROW
    MOV [DI+1],AL

    MOV AL,EDITOR_COL
    MOV [DI+2],AL

    INC PLACEDCOUNT2

G20_END:

    POP DI
    POP CX
    POP BX
    POP AX

    RET

G20ADD2 ENDP

; Dibuja la imagen 2 (sin transparencia, todo el rectangulo es opaco)

DRAW_IMAGE2 PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI

    MOV AL,EDITOR_ROW
    MOV IMG2_SROW,AL

    MOV AL,EDITOR_COL
    MOV IMG2_SCOL,AL

    MOV IMG2_R,0

DI2_ROWLOOP:

    MOV AL,IMG2_R
    CMP AL,IMG2_ROWS
    JB DI2_ROW_OK

    JMP DI2_DONE

DI2_ROW_OK:

    MOV AL,IMG2_SROW
    ADD AL,IMG2_R

    CMP AL,IMG2_BOTTOM
    JBE DI2_ROW_VISIBLE

    JMP DI2_DONE

DI2_ROW_VISIBLE:

    MOV IMG2_C,0

DI2_COLLOOP:

    MOV AL,IMG2_C
    CMP AL,IMG2_COLS
    JB DI2_COL_OK

    JMP DI2_NEXTROW

DI2_COL_OK:

    MOV AL,IMG2_SCOL
    ADD AL,IMG2_C

    CMP AL,IMG2_RIGHT
    JBE DI2_COL_VISIBLE

    JMP DI2_NEXTCOL

DI2_COL_VISIBLE:

    XOR AX,AX
    MOV AL,IMG2_R

    MOV BL,IMG2_COLS
    MUL BL

    XOR BX,BX
    MOV BL,IMG2_C

    ADD AX,BX

    MOV SI,OFFSET IMG2_DATA
    ADD SI,AX

    MOV AL,[SI]
    MOV BL,AL

    MOV AH,02H
    MOV BH,00H

    MOV DH,IMG2_SROW
    ADD DH,IMG2_R

    MOV DL,IMG2_SCOL
    ADD DL,IMG2_C

    INT 10H

    MOV AH,09H
    MOV AL,IMG2_CHAR
    MOV BH,00H
    MOV CX,0001H

    INT 10H

DI2_NEXTCOL:

    INC IMG2_C
    JMP DI2_COLLOOP

DI2_NEXTROW:

    INC IMG2_R
    JMP DI2_ROWLOOP

DI2_DONE:

    CALL UPDATE_CURSOR

    POP SI
    POP DX
    POP CX
    POP BX
    POP AX

    RET

DRAW_IMAGE2 ENDP

; Restaura la imagen 2 despues de escribir sobre ella
; Se llama desde STORE_CHAR y CLEAR_CHAR para que la imagen quede
; siempre por encima del texto

PUBLIC RESTORE_IMAGE2_PIXEL

RESTORE_IMAGE2_PIXEL PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI

    XOR SI,SI

RIP2_LOOP:

    MOV AX,SI
    CMP AX,PLACEDCOUNT2
    JB RIP2_ENTRY_OK

    JMP RIP2_DONE

RIP2_ENTRY_OK:

    MOV AX,SI
    MOV CX,3
    MUL CX

    MOV DI,OFFSET PLACED2
    ADD DI,AX

    XOR AX,AX
    MOV AL,EDITOR_ROW

    XOR CX,CX
    MOV CL,[DI+1]

    SUB AX,CX

    JNS RIP2_ROW_POS

    JMP RIP2_NEXT

RIP2_ROW_POS:

    CMP AX,IMG2_ROWS
    JB RIP2_ROW_OK

    JMP RIP2_NEXT

RIP2_ROW_OK:

    MOV DX,AX

    XOR AX,AX
    MOV AL,EDITOR_COL

    XOR CX,CX
    MOV CL,[DI+2]

    SUB AX,CX

    JNS RIP2_COL_POS

    JMP RIP2_NEXT

RIP2_COL_POS:

    CMP AX,IMG2_COLS
    JB RIP2_COL_OK

    JMP RIP2_NEXT

RIP2_COL_OK:

    PUSH AX

    MOV AX,DX
    MOV CX,IMG2_COLS
    MUL CX

    POP CX

    ADD AX,CX

    MOV BX,OFFSET IMG2_DATA
    ADD BX,AX

    MOV AL,[BX]
    MOV BL,AL

    MOV AH,02H
    MOV BH,00H
    MOV DH,EDITOR_ROW
    MOV DL,EDITOR_COL

    INT 10H

    MOV AH,09H
    MOV AL,IMG2_CHAR
    MOV BH,00H
    MOV CX,0001H

    INT 10H

RIP2_NEXT:

    INC SI
    JMP RIP2_LOOP

RIP2_DONE:

    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX

    RET

RESTORE_IMAGE2_PIXEL ENDP

