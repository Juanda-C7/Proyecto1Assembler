    MOV BP,OFFSET PRESS_KEY
    MOV CX,36
    MOV DH,14
    MOV DL,22
    MOV BL,1FH
    CALL PRINT_AT

    POP BP
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX

    RET

SHOWERR ENDP

; Dibuja en pantalla el texto ya cargado en el buffer del editor
; Se llama despues de DRAW_EDITOR y antes de EDITOR_LOOP

PUBLIC DRAWTEXT

DRAWTEXT PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI

    XOR SI,SI

DT_LOOP:

    CMP SI,1840
    JAE DT_DONE

    MOV AX,SI
    MOV BL,OPEN_COLS

    DIV BL

    MOV DH,AL
    ADD DH,OPEN_TOP
    MOV DL,AH

    MOV AH,02H
    MOV BH,00H

    INT 10H

    MOV DI,OFFSET TEXT_BUFFER
    ADD DI,SI
    MOV AL,[DI]

    MOV DI,OFFSET ATTR_BUFFER
    ADD DI,SI
    MOV BL,[DI]

    MOV AH,09H
    MOV BH,00H
    MOV CX,0001H

    INT 10H

    INC SI

    JMP DT_LOOP

DT_DONE:

    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX

    RET

DRAWTEXT ENDP

; Alterna el color de fondo para lo que se va a escribir con ALT+N
; Solo cambia el nibble alto (fondo) de EDITOR_ATTRIB, deja igual el nibble
; bajo (letra), y no afecta el texto que ya esta escrito en pantalla

PUBLIC ALTN

ALTN PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX

    INC BG_INDEX

    CMP BG_INDEX,04H
    JB ALTN_SET

    MOV BG_INDEX,00H

ALTN_SET:

    XOR BX,BX
    MOV BL,BG_INDEX

    MOV AL,BG_COLORS[BX]
    MOV CL,04H
    SHL AL,CL

    AND EDITOR_ATTRIB,0FH
    OR EDITOR_ATTRIB,AL

    POP CX
    POP BX
    POP AX

    RET

ALTN ENDP

