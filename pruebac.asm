    MOV BX,DI
    ADD BX,2
    MOV ES:[BX],AL
    MOV BX,DI
    SUB BX,640
    MOV ES:[BX],AL
    MOV BX,DI
    ADD BX,640
    MOV ES:[BX],AL

    POP ES
    POP DI
    POP DX
    POP CX
    POP BX
    POP AX
    RET
I10CURSOR ENDP

