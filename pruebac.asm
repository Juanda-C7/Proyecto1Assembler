A10MAIN PROC FAR
    MOV AX,@DATA
    MOV DS,AX
    MOV ES,AX

    MOV AH,0FH
    INT 10H
    PUSH AX

    CALL B10MODE
    CALL C10SETPAL
    CALL D10CLRSCRN
    CALL I10CURSOR

A20:
    CALL H10INPUT
    CMP EXIT,1
    JE A90
    CMP REFRESH,0
    JE A20
    CALL E10REDRAW
    JMP A20

A90:
    POP AX
    MOV AH,00H
    INT 10H
    MOV AX,4C00H
    INT 21H
A10MAIN ENDP

 ; Activa modo VGA 13h.
B10MODE PROC NEAR
    MOV AX,0013H
    INT 10H
    RET
B10MODE ENDP

 ; Carga la paleta personalizada.
C10SETPAL PROC NEAR
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI

    MOV SI,OFFSET PALTABLE
    XOR DI,DI
C20:
    CMP DI,PALCOUNT
    JGE C90
    MOV AL,[SI]
    XOR AH,AH
    MOV BX,AX
    MOV DH,[SI+1]
    MOV CH,[SI+2]
    MOV CL,[SI+3]
    MOV AX,1010H
    INT 10H
    ADD SI,4
    INC DI
    JMP C20
C90:
    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX
    RET
C10SETPAL ENDP

 ; Rellena la pantalla con el color de fondo.
D10CLRSCRN PROC NEAR
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH SI
    PUSH DI
    PUSH ES

    MOV AX,0A000H
    MOV ES,AX
    XOR DI,DI
    XOR BX,BX
    MOV BL,BGINDEX
    MOV SI,BX
    MOV AL,BGCOLORS[SI]
    MOV CX,64000
    REP STOSB

    POP ES
    POP DI
    POP SI
    POP CX
    POP BX
    POP AX
    RET
D10CLRSCRN ENDP

 ; Redibuja todas las imagenes guardadas.
E10REDRAW PROC NEAR
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI

    CALL D10CLRSCRN
    XOR SI,SI
E20:
    MOV AX,SI
    CMP AX,PLACEDCOUNT
    JGE E30

    MOV AX,SI
    MOV CX,6
    MUL CX
    MOV DI,OFFSET PLACED
    ADD DI,AX

    MOV AL,[DI]
    MOV CX,[DI+1]
    MOV DX,[DI+3]
    MOV BL,[DI+5]

    PUSH SI
    CMP AL,1
    JNE E21
    MOV SI,OFFSET IMG1
    JMP E22
E21:
    CMP AL,2
    JNE E21B
    MOV SI,OFFSET IMG2
    JMP E22
E21B:
    MOV SI,OFFSET IMG3
E22:
    MOV [SI+4],CX
    MOV [SI+6],DX
    CALL F10DISPLY
    POP SI

    INC SI
    JMP E20

E30:
    CALL I10CURSOR
    MOV REFRESH,0
    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX
    RET
E10REDRAW ENDP

 ; Pinta una matriz usando X, Y y flip de su estructura.
F10DISPLY PROC NEAR
    PUSHA
    PUSH ES

    MOV DIMG_FLIP,BL
    MOV CX,SI[4]
    MOV DX,SI[6]
    MOV DIMG_X,CX
    MOV DIMG_Y,DX

    MOV AX,SI[0]
    MOV DIMG_W,AX
    MOV AX,SI[2]
    MOV DIMG_H,AX
    LEA DI,SI[8]
    MOV DIMG_PTR,DI

    MOV AX,0A000H
    MOV ES,AX
    MOV ROWCNT,0

F20:
    MOV AX,ROWCNT
    CMP AX,DIMG_H
    JGE F90

    MOV AX,DIMG_Y
    ADD AX,ROWCNT
    MOV BX,320
    MUL BX
    ADD AX,DIMG_X
    MOV DI,AX

    MOV AX,ROWCNT
    MOV BX,DIMG_W
    MUL BX
    ADD AX,DIMG_PTR
    MOV SI,AX

    CMP DIMG_FLIP,0
    JE F30

    ADD SI,DIMG_W
    DEC SI
    MOV COLCNT,0
F25:
    MOV AX,COLCNT
    CMP AX,DIMG_W
    JGE F40
    MOV AL,[SI]
    CMP AL,TRANSP
    JE F26
    MOV ES:[DI],AL
F26:
    DEC SI
    INC DI
    INC COLCNT
    JMP F25

F30:
    MOV COLCNT,0
F35:
    MOV AX,COLCNT
    CMP AX,DIMG_W
    JGE F40
    MOV AL,[SI]
    CMP AL,TRANSP
    JE F36
    MOV ES:[DI],AL
F36:
    INC SI
    INC DI
    INC COLCNT
    JMP F35

F40:
    INC ROWCNT
    JMP F20
F90:
    POP ES
    POPA
    RET
F10DISPLY ENDP

 ; Guarda una nueva imagen en PLACED.
G10ADD PROC NEAR
    MOV NEWID,AL
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH DI

    MOV DX,PLACEDCOUNT
    CMP DX,MAXPLACED
    JGE G90

    MOV AX,DX
    MOV CX,6
    MUL CX
    MOV DI,OFFSET PLACED
    ADD DI,AX

    MOV AL,NEWID
    MOV [DI],AL
    MOV AX,CURSORX
    MOV [DI+1],AX
    MOV AX,CURSORY
    MOV [DI+3],AX
    MOV AL,CURFLIP
    MOV [DI+5],AL

    INC PLACEDCOUNT
    MOV CURFLIP,0
    MOV REFRESH,1
G90:
    POP DI
    POP DX
    POP CX
    POP BX
    POP AX
    RET
G10ADD ENDP

 ; Procesa flechas, ESC y combinaciones ALT.
H10INPUT PROC NEAR
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX

    MOV AH,01H
    INT 16H
    JZ H90

    MOV AH,02H
    INT 16H
    MOV DL,AL

    MOV AH,00H
    INT 16H
    MOV BL,AH

    CMP AL,1BH
    JNE H10A
    MOV EXIT,1
    JMP H90

H10A:
    CMP BL,SC_UP
    JNE H10B
    MOV AX,CURSORY
    SUB AX,STEP
    CMP AX,0
    JGE H10AOK
    XOR AX,AX
H10AOK:
    MOV CURSORY,AX
    MOV REFRESH,1
    JMP H90

H10B:
    CMP BL,SC_DOWN
    JNE H10C
    MOV AX,CURSORY
    ADD AX,STEP
    CMP AX,MAXY
    JLE H10BOK
    MOV AX,MAXY
H10BOK:
    MOV CURSORY,AX
    MOV REFRESH,1
    JMP H90

H10C:
    CMP BL,SC_LEFT
    JNE H10D
    MOV AX,CURSORX
    SUB AX,STEP
    CMP AX,0
    JGE H10COK
    XOR AX,AX
H10COK:
    MOV CURSORX,AX
    MOV REFRESH,1
    JMP H90

H10D:
    CMP BL,SC_RIGHT
    JNE H10E
    MOV AX,CURSORX
    ADD AX,STEP
    CMP AX,MAXX
    JLE H10DOK
    MOV AX,MAXX
H10DOK:
    MOV CURSORX,AX
    MOV REFRESH,1
    JMP H90

H10E:
    TEST DL,ALT_FLAG
    JZ H90

    CMP BL,SC_ALTM
    JNE H10F
    MOV AL,BGINDEX
    INC AL
    CMP AL,3
    JL H10EOK
    XOR AL,AL
H10EOK:
    MOV BGINDEX,AL
    MOV REFRESH,1
    JMP H90

H10F:
    CMP BL,SC_ALTI
    JNE H10G
    MOV AL,1
    CALL G10ADD
    JMP H90

H10G:
    CMP BL,SC_ALTJ
    JNE H10H
    MOV AL,2
    CALL G10ADD
    JMP H90

H10H:
    CMP BL,SC_ALTK
    JNE H10I
    MOV AL,3
    CALL G10ADD
    JMP H90

H10I:
    CMP BL,SC_ALTR
    JNE H10J
    MOV AL,CURFLIP
    XOR AL,1
    MOV CURFLIP,AL
    MOV REFRESH,1
    JMP H90

H10J:
    CMP BL,SC_ALTC
    JNE H90
    MOV PLACEDCOUNT,0
    MOV CURFLIP,0
    MOV REFRESH,1

H90:
    POP DX
    POP CX
    POP BX
    POP AX
    RET
H10INPUT ENDP

 ; Dibuja el cursor en la posicion actual.
