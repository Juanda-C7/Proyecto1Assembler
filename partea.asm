; Lee el nombre del archivo tecla por tecla con validacion en vivo

GET_FILENAME_INPUT PROC NEAR

    PUSH BX
    PUSH CX
    PUSH DX
    PUSH DI

    MOV BYTE PTR INPUT_NAME+1,00H

GFI_READ:

    MOV AH,10H
    INT 16H

    CMP AX,2D00H
    JNE GFI_CHECK_ALTZ
    JMP GFI_CANCEL

GFI_CHECK_ALTZ:

    CMP AX,2C00H
    JNE GFI_CHECK_ENTER
    JMP GFI_CANCEL

GFI_CHECK_ENTER:

    CMP AL,0DH
    JNE GFI_CHECK_BACK
    JMP GFI_DONE

GFI_CHECK_BACK:

    CMP AL,08H
    JNE GFI_CHECK_CHAR
    JMP GFI_BACKSPACE

; Agrega el caracter escrito y valida la longitud en vivo

GFI_CHECK_CHAR:

    CMP AL,00H
    JE GFI_READ

    MOV DL,BYTE PTR INPUT_NAME+1
    CMP DL,MAXINPUT
    JAE GFI_READ

    XOR BX,BX
    MOV BL,DL
    LEA DI,INPUT_NAME+2
    ADD DI,BX
    MOV [DI],AL

    INC BYTE PTR INPUT_NAME+1

    MOV DL,AL
    MOV AH,02H
    INT 21H

    MOV AL,BYTE PTR INPUT_NAME+1
    CMP AL,08H
    JBE GFI_READ

    CALL SHOW_LENGTH_ALERT

    JMP GFI_READ

; Borra el ultimo caracter escrito

GFI_BACKSPACE:

    CMP BYTE PTR INPUT_NAME+1,00H
    JE GFI_READ

    DEC BYTE PTR INPUT_NAME+1

    MOV AH,03H
    MOV BH,00H
    INT 10H

    DEC DL

    MOV AH,02H
    MOV BH,00H
    INT 10H

    MOV DL,' '
    MOV AH,02H
    INT 21H

    MOV AH,03H
    MOV BH,00H
    INT 10H

    DEC DL

    MOV AH,02H
    MOV BH,00H
    INT 10H

    MOV AL,BYTE PTR INPUT_NAME+1
    CMP AL,08H
    JBE GFI_HIDE_ALERT

    JMP GFI_READ

GFI_HIDE_ALERT:

    CALL HIDE_LENGTH_ALERT

    JMP GFI_READ

GFI_CANCEL:

    MOV AL,0FFH
    JMP GFI_END

GFI_DONE:

    MOV AL,00H

GFI_END:

    POP DI
    POP DX
    POP CX
    POP BX

    RET

GET_FILENAME_INPUT ENDP

; Crea el archivo y valida su nombre

CREATE_FILE PROC NEAR

    CALL SHOW_CREATE_SCREEN
    CALL GET_FILENAME_INPUT

    CMP AL,0FFH
    JNE CREATE_CHECK_EMPTY
    RET

CREATE_CHECK_EMPTY:

    CMP BYTE PTR INPUT_NAME+1,00H
    JNE CREATE_CHECK_LENGTH
    JMP CREATE_EMPTY_ERROR

CREATE_EMPTY_ERROR:

    MOV ERROR_CODE,01H
    MOV AL,01H
    RET

CREATE_CHECK_LENGTH:

    CMP BYTE PTR INPUT_NAME+1,08H
    JBE CREATE_CHECK_CHARS
    JMP CREATE_LONG_ERROR

CREATE_LONG_ERROR:

    MOV ERROR_CODE,02H
    MOV AL,01H
    RET

CREATE_CHECK_CHARS:

    CALL PROCESS_NAME

    CMP AL,00H
    JE CREATE_BUILD_NAME
    JMP CREATE_CHAR_ERROR

CREATE_CHAR_ERROR:

    MOV ERROR_CODE,03H
    MOV AL,01H
    RET

CREATE_BUILD_NAME:

    CALL BUILD_FILENAME

    LEA DX,FILE_NAME
    MOV CX,0000H
    MOV AH,5BH

    INT 21H

    JNC CREATE_SUCCESS
    JMP CREATE_DOS_ERROR

CREATE_SUCCESS:

    MOV FILE_HANDLE,AX
    MOV AL,00H
    RET

CREATE_DOS_ERROR:

    CMP AX,0050H
    JNE CREATE_ERROR_PATH
    JMP CREATE_EXISTS_ERROR

CREATE_EXISTS_ERROR:

    MOV ERROR_CODE,04H
    MOV AL,01H
    RET

CREATE_ERROR_PATH:

    CMP AX,0003H
    JNE CREATE_ERROR_ACCESS
    JMP CREATE_PATH_ERROR

CREATE_PATH_ERROR:

    MOV ERROR_CODE,05H
    MOV AL,01H
    RET

CREATE_ERROR_ACCESS:

    CMP AX,0005H
    JNE CREATE_ERROR_FILES
    JMP CREATE_ACCESS_ERROR

CREATE_ACCESS_ERROR:

    MOV ERROR_CODE,06H
    MOV AL,01H
    RET

CREATE_ERROR_FILES:

    CMP AX,0004H
    JNE CREATE_ERROR_OTHER
    JMP CREATE_FILES_ERROR

CREATE_FILES_ERROR:

    MOV ERROR_CODE,07H
    MOV AL,01H
    RET

CREATE_ERROR_OTHER:

    MOV ERROR_CODE,08H
    MOV AL,01H
    RET

CREATE_FILE ENDP

; Valida caracteres y convierte el nombre a mayusculas

PROCESS_NAME PROC NEAR

    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI

    XOR CX,CX
    MOV CL,BYTE PTR INPUT_NAME+1

    LEA SI,INPUT_NAME+2

PN_LOOP:

    CMP CX,0000H
    JE PN_VALID
    JMP PN_CHECK_CHAR

PN_CHECK_CHAR:

    MOV AL,[SI]

    CMP AL,'A'
    JB PN_CHECK_LOWER

    CMP AL,'Z'
    JBE PN_NEXT

    JMP PN_CHECK_LOWER

PN_CHECK_LOWER:

    CMP AL,'a'
    JB PN_CHECK_DIGIT

    CMP AL,'z'
    JA PN_CHECK_DIGIT

    JMP PN_UPPER

PN_UPPER:

    SUB AL,20H
    MOV [SI],AL

    JMP PN_NEXT

PN_CHECK_DIGIT:

    CMP AL,'0'
    JB PN_INVALID

    CMP AL,'9'
    JA PN_INVALID

    JMP PN_NEXT

PN_NEXT:

    INC SI
    DEC CX

    JMP PN_LOOP

PN_INVALID:

    MOV AL,01H
    JMP PN_END

PN_VALID:

    MOV AL,00H

PN_END:

    POP SI
    POP DX
    POP CX
    POP BX

    RET

PROCESS_NAME ENDP

; Agrega la extension FDJ al nombre del archivo

BUILD_FILENAME PROC NEAR

    PUSH AX
    PUSH CX
    PUSH SI
    PUSH DI

    LEA SI,INPUT_NAME+2
    LEA DI,FILE_NAME

    XOR CX,CX
    MOV CL,BYTE PTR INPUT_NAME+1

BF_COPY:

    CMP CX,0000H
    JE BF_EXTENSION

    MOV AL,[SI]
    MOV [DI],AL

    INC SI
    INC DI
    DEC CX

    JMP BF_COPY

BF_EXTENSION:

    MOV BYTE PTR [DI],'.'
    INC DI

    MOV BYTE PTR [DI],'F'
    INC DI

    MOV BYTE PTR [DI],'D'
    INC DI

    MOV BYTE PTR [DI],'J'
    INC DI

    MOV BYTE PTR [DI],00H

    POP DI
    POP SI
    POP CX
    POP AX

    RET

BUILD_FILENAME ENDP

