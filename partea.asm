A10MAIN PROC FAR

    MOV AX,@DATA
    MOV DS,AX
    MOV ES,AX

    CALL C10SETPAL

A20:

    CALL B10MENU

    MOV ROW,FIRSTROW
    MOV ATTRIB,1EH

    CALL D10DISPLY
    CALL C10INPUT

    CMP AX,0100H
    JNE A20_CHECK_OPEN
    JMP A20_CREATE

A20_CHECK_OPEN:

    CMP AX,0200H
    JNE A20_CHECK_EXIT
    JMP A20_OPEN

A20_CHECK_EXIT:

    CMP AX,0300H
    JNE A20_CHECK_ALTX
    JMP A20_EXIT

A20_CHECK_ALTX:

    CMP AX,0400H
    JNE A20
    JMP A20_EXIT

; Controla la opcion de crear archivo

A20_CREATE:

    CALL CREATE_FILE

    CMP AL,0FFH
    JNE A20_CREATE_CHECKERR
    JMP A20

A20_CREATE_CHECKERR:

    CMP AL,00H
    JNE A20_CREATE_ERROR
    JMP A20_CREATE_EDITOR

A20_CREATE_ERROR:

    CALL SHOW_CREATE_ERROR
    CALL WAIT_KEY
    JMP A20

A20_CREATE_EDITOR:

    CALL EDITOR_INIT
    JMP A20_EDITOR_START

; Controla la opcion de abrir archivo

A20_OPEN:

    CALL Q10CLEAR

    MOV BP,OFFSET MSG_OPEN
    MOV CX,25
    MOV DH,10
    MOV DL,28
    MOV BL,1FH
    CALL PRINT_AT

    CALL WAIT_KEY
    CALL Q10CLEAR

    JMP A20

; Inicia el editor de texto

A20_EDITOR_START:

    CALL DRAW_EDITOR
    CALL EDITOR_LOOP

    CMP AL,01H
    JNE A20_CHECK_EDITOR_MENU

    JMP A20_EDITOR_SAVE_EXIT

A20_CHECK_EDITOR_MENU:

    CMP AL,02H
    JNE A20_EDITOR_RETURN

    JMP A20

A20_EDITOR_RETURN:

    JMP A20

; Guarda el archivo y sale con ALT+X

A20_EDITOR_SAVE_EXIT:

    CALL SAVE_FILE
    JMP A20_EXIT

; Termina el programa

A20_EXIT:

    MOV AX,4C00H
    INT 21H

A10MAIN ENDP

; Configura los colores personalizados del editor

C10SETPAL PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI

    MOV SI,OFFSET PALTABLE
    XOR DI,DI

CSP_LOOP:

    CMP DI,PALCOUNT
    JGE CSP_DONE

    MOV AL,[SI]
    XOR AH,AH
    MOV BX,AX

    MOV DH,[SI+1]
    MOV CH,[SI+2]
    MOV CL,[SI+3]

    MOV AX,1010H
    INT 10H

    ADD SI,4
    INC DI
    JMP CSP_LOOP

CSP_DONE:

    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX

    RET

C10SETPAL ENDP

