C10INPUT PROC NEAR

C10_READ:

    MOV AH,10H
    INT 16H

    CMP AH,50H
    JNE C10_CHECK_UP
    JMP C10_DOWN

C10_CHECK_UP:

    CMP AH,48H
    JNE C10_CHECK_ENTER
    JMP C10_UP

C10_CHECK_ENTER:

    CMP AL,0DH
    JNE C10_CHECK_ALTX
    JMP C10_ENTER

C10_CHECK_ALTX:

    CMP AX,2D00H
    JNE C10_READ
    JMP C10_ALTX

C10_DOWN:

    CMP ROW,LASTROW
    JAE C10_READ

    MOV ATTRIB,1FH
    CALL D10DISPLY

    INC ROW

    MOV ATTRIB,1EH
    CALL D10DISPLY

    JMP C10_READ

C10_UP:

    CMP ROW,FIRSTROW
    JBE C10_READ

    MOV ATTRIB,1FH
    CALL D10DISPLY

    DEC ROW

    MOV ATTRIB,1EH
    CALL D10DISPLY

    JMP C10_READ

C10_ENTER:

    CMP ROW,FIRSTROW
    JNE C10_ENTER_OPEN

    MOV AX,0100H
    RET

C10_ENTER_OPEN:

    CMP ROW,FIRSTROW+1
    JNE C10_ENTER_EXIT

    MOV AX,0200H
    RET

C10_ENTER_EXIT:

    MOV AX,0300H
    RET

C10_ALTX:

    MOV AX,0400H
    RET

