; Controla la escritura, navegacion y atajos del editor

EDITOR_LOOP PROC NEAR

EL_READ:

    MOV AH,01H
    INT 16H

    JZ EL_READ

    MOV AH,02H
    INT 16H

    MOV DL,AL

    MOV AH,00H
    INT 16H

    MOV BL,AH

    TEST DL,08H
    JNZ EL_ALT_KEY

    JMP EL_NORMAL_KEY

; Controla las teclas ALT del editor

EL_ALT_KEY:

    CMP BL,32H
    JNE EL_CHECK_ALTC

    JMP EL_ALTM

EL_CHECK_ALTC:

    CMP BL,2EH
    JNE EL_CHECK_ALTU

    JMP EL_ALTC

EL_CHECK_ALTU:

    CMP BL,16H
    JNE EL_CHECK_ALTI

    JMP EL_ALTU

EL_CHECK_ALTI:

    CMP BL,17H
    JNE EL_CHECK_ALTX_ALT

    JMP EL_ALTI

EL_CHECK_ALTX_ALT:

    CMP BL,2DH
    JNE EL_CHECK_ALTZ

    JMP EL_ALTX

EL_CHECK_ALTZ:

    CMP BL,2CH
    JNE EL_NORMAL_KEY

    JMP EL_ALTZ

; Controla las teclas normales del editor

EL_NORMAL_KEY:

    CMP BL,4BH
    JNE EL_CHECK_RIGHT

    JMP EL_LEFT

EL_CHECK_RIGHT:

    CMP BL,4DH
    JNE EL_CHECK_UP

    JMP EL_RIGHT

EL_CHECK_UP:

    CMP BL,48H
    JNE EL_CHECK_DOWN

    JMP EL_UP

EL_CHECK_DOWN:

    CMP BL,50H
    JNE EL_CHECK_ENTER

    JMP EL_DOWN

EL_CHECK_ENTER:

    CMP AL,0DH
    JNE EL_CHECK_BACKSPACE

    JMP EL_ENTER

EL_CHECK_BACKSPACE:

    CMP AL,08H
    JNE EL_CHECK_COLON

    JMP EL_BACKSPACE

; Reconoce los dos puntos como caracter permitido

EL_CHECK_COLON:

    CMP AX,3E34H
    JNE EL_CHECK_TEXT

    MOV AL,':'

    JMP EL_CHECK_TEXT

; Valida los caracteres permitidos para escribir

EL_CHECK_TEXT:

    PUSH AX

    CALL VALIDATE_TEXT_CHAR

    CMP AL,01H

    POP AX

    JE EL_TEXT_VALID

    JMP EL_READ

EL_TEXT_VALID:

    JMP EL_WRITE

; Escribe el caracter en el editor

EL_WRITE:

    PUSH AX

    CALL GET_BUFFER_POSITION

    POP AX

    MOV [DI],AL

    MOV AH,09H
    MOV BH,00H
    MOV BL,EDITOR_ATTRIB
    MOV CX,0001H

    INT 10H

    CALL RESTORE_IMAGE_PIXEL
    CALL MOVE_CURSOR_RIGHT

    JMP EL_READ

; Mueve el cursor a la siguiente linea

EL_ENTER:

    MOV EDITOR_COL,EDITOR_LEFT

    INC EDITOR_ROW

    CMP EDITOR_ROW,EDITOR_BOTTOM
    JBE EL_ENTER_CURSOR

    JMP EL_ENTER_LIMIT

EL_ENTER_LIMIT:

    MOV EDITOR_ROW,EDITOR_BOTTOM

EL_ENTER_CURSOR:

    CALL UPDATE_CURSOR

    JMP EL_READ

; Borra el caracter anterior

EL_BACKSPACE:

    CMP EDITOR_COL,EDITOR_LEFT
    JNE EL_BACKSPACE_DELETE

    JMP EL_BACKSPACE_END

EL_BACKSPACE_DELETE:

    DEC EDITOR_COL

    CALL GET_BUFFER_POSITION

    MOV BYTE PTR [DI],' '

    MOV AH,02H
    MOV BH,00H
    MOV DH,EDITOR_ROW
    MOV DL,EDITOR_COL

    INT 10H

    MOV AL,' '
    MOV AH,09H
    MOV BH,00H
    MOV BL,EDITOR_ATTRIB
    MOV CX,0001H

    INT 10H

    CALL RESTORE_IMAGE_PIXEL

EL_BACKSPACE_END:

    CALL UPDATE_CURSOR

    JMP EL_READ

; Mueve el cursor hacia la izquierda

EL_LEFT:

    CMP EDITOR_COL,EDITOR_LEFT
    JNE EL_LEFT_MOVE

    JMP EL_READ

EL_LEFT_MOVE:

    DEC EDITOR_COL
    CALL UPDATE_CURSOR

    JMP EL_READ

; Mueve el cursor hacia la derecha

EL_RIGHT:

    CMP EDITOR_COL,EDITOR_RIGHT
    JB EL_RIGHT_MOVE

    JMP EL_READ

EL_RIGHT_MOVE:

    INC EDITOR_COL
    CALL UPDATE_CURSOR

    JMP EL_READ

; Mueve el cursor hacia arriba

EL_UP:

    CMP EDITOR_ROW,EDITOR_TOP
    JA EL_UP_MOVE

    JMP EL_READ

EL_UP_MOVE:

    DEC EDITOR_ROW
    CALL UPDATE_CURSOR

    JMP EL_READ

; Mueve el cursor hacia abajo

EL_DOWN:

    CMP EDITOR_ROW,EDITOR_BOTTOM
    JB EL_DOWN_MOVE

    JMP EL_READ

EL_DOWN_MOVE:

    INC EDITOR_ROW
    CALL UPDATE_CURSOR

    JMP EL_READ

; Cambia el color de la letra con ALT+M

EL_ALTM:

    INC EDITOR_COLOR

    CMP EDITOR_COLOR,03H
    JB EL_ALTM_SET

    MOV EDITOR_COLOR,00H

EL_ALTM_SET:

    XOR BX,BX
    MOV BL,EDITOR_COLOR

    MOV AL,TEXT_COLORS[BX]
    MOV EDITOR_ATTRIB,AL

    CALL UPDATE_CURSOR

    JMP EL_READ

; Centra el cursor con ALT+C

EL_ALTC:

    MOV EDITOR_COL,EDITOR_CENTER

    CALL UPDATE_CURSOR

    JMP EL_READ

; Lleva el cursor arriba con ALT+U

EL_ALTU:

    MOV EDITOR_ROW,EDITOR_TOP

    CALL UPDATE_CURSOR

    JMP EL_READ

; Coloca la imagen con ALT+I

EL_ALTI:

    CALL G10ADD
    CALL DRAW_IMAGE1

    JMP EL_READ

; Guarda y sale con ALT+X

EL_ALTX:

    MOV AL,01H

    RET

; Regresa al menu con ALT+Z

EL_ALTZ:

    MOV AL,02H

    RET

EDITOR_LOOP ENDP

; Registra la posicion de una imagen colocada

G10ADD PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DI

    MOV BX,PLACEDCOUNT
    CMP BX,MAXPLACED
    JB G10_SPACE_OK

    JMP G10_END

G10_SPACE_OK:

    MOV AX,BX
    MOV CX,3
    MUL CX

    MOV DI,OFFSET PLACED
    ADD DI,AX

    MOV BYTE PTR [DI],01H

    MOV AL,EDITOR_ROW
    MOV [DI+1],AL

    MOV AL,EDITOR_COL
    MOV [DI+2],AL

    INC PLACEDCOUNT

G10_END:

    POP DI
    POP CX
    POP BX
    POP AX

    RET

G10ADD ENDP

; Restaura la imagen despues de escribir sobre ella

RESTORE_IMAGE_PIXEL PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI

    XOR SI,SI

RIP_LOOP:

    MOV AX,SI
    CMP AX,PLACEDCOUNT
    JB RIP_ENTRY_OK

    JMP RIP_DONE

RIP_ENTRY_OK:

    MOV AX,SI
    MOV CX,3
    MUL CX

    MOV DI,OFFSET PLACED
    ADD DI,AX

    XOR AX,AX
    MOV AL,EDITOR_ROW

    XOR CX,CX
    MOV CL,[DI+1]

    SUB AX,CX

    JNS RIP_ROW_POS

    JMP RIP_NEXT

RIP_ROW_POS:

    CMP AX,IMG1_ROWS
    JB RIP_ROW_OK

    JMP RIP_NEXT

RIP_ROW_OK:

    MOV DX,AX

    XOR AX,AX
    MOV AL,EDITOR_COL

    XOR CX,CX
    MOV CL,[DI+2]

    SUB AX,CX

    JNS RIP_COL_POS

    JMP RIP_NEXT

RIP_COL_POS:

    CMP AX,IMG1_COLS
    JB RIP_COL_OK

    JMP RIP_NEXT

RIP_COL_OK:

    PUSH AX

    MOV AX,DX
    MOV CX,IMG1_COLS
    MUL CX

    POP CX

    ADD AX,CX

    MOV BX,OFFSET IMG1_DATA
    ADD BX,AX

    MOV AL,[BX]

    CMP AL,IMG_TRANSP
    JNE RIP_DRAW_PIXEL

    JMP RIP_NEXT

RIP_DRAW_PIXEL:

    MOV BL,AL

    MOV AH,02H
    MOV BH,00H
    MOV DH,EDITOR_ROW
    MOV DL,EDITOR_COL

    INT 10H

    MOV AH,09H
    MOV AL,IMG_CHAR
    MOV BH,00H
    MOV CX,0001H

    INT 10H

RIP_NEXT:

    INC SI
    JMP RIP_LOOP

RIP_DONE:

    CALL UPDATE_CURSOR

    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX

    RET

RESTORE_IMAGE_PIXEL ENDP

; Dibuja la imagen del editor

DRAW_IMAGE1 PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI

    MOV AL,EDITOR_ROW
    MOV IMG_SROW,AL

    MOV AL,EDITOR_COL
    MOV IMG_SCOL,AL

    MOV IMG_R,0

DI_ROWLOOP:

    MOV AL,IMG_R
    CMP AL,IMG1_ROWS
    JB DI_ROW_OK

    JMP DI_DONE

DI_ROW_OK:

    MOV AL,IMG_SROW
    ADD AL,IMG_R

    CMP AL,EDITOR_BOTTOM
    JBE DI_ROW_VISIBLE

    JMP DI_DONE

DI_ROW_VISIBLE:

    MOV IMG_C,0

DI_COLLOOP:

    MOV AL,IMG_C
    CMP AL,IMG1_COLS
    JB DI_COL_OK

    JMP DI_NEXTROW

DI_COL_OK:

    MOV AL,IMG_SCOL
    ADD AL,IMG_C

    CMP AL,EDITOR_RIGHT
    JBE DI_COL_VISIBLE

    JMP DI_NEXTCOL

DI_COL_VISIBLE:

    XOR AX,AX
    MOV AL,IMG_R

    MOV BL,IMG1_COLS
    MUL BL

    XOR BX,BX
    MOV BL,IMG_C

    ADD AX,BX

    MOV SI,OFFSET IMG1_DATA
    ADD SI,AX

    MOV AL,[SI]

    CMP AL,IMG_TRANSP
    JNE DI_DRAW_PIXEL

    JMP DI_NEXTCOL

DI_DRAW_PIXEL:

    MOV BL,AL

    MOV AH,02H
    MOV BH,00H

    MOV DH,IMG_SROW
    ADD DH,IMG_R

    MOV DL,IMG_SCOL
    ADD DL,IMG_C

    INT 10H

    MOV AH,09H
    MOV AL,IMG_CHAR
    MOV BH,00H
    MOV CX,0001H

    INT 10H

DI_NEXTCOL:

    INC IMG_C
    JMP DI_COLLOOP

DI_NEXTROW:

    INC IMG_R
    JMP DI_ROWLOOP

DI_DONE:

    CALL UPDATE_CURSOR

    POP SI
    POP DX
    POP CX
    POP BX
    POP AX

    RET

DRAW_IMAGE1 ENDP

; Valida los caracteres permitidos en el texto

VALIDATE_TEXT_CHAR PROC NEAR

    CMP AL,' '
    JE VTC_OK

    CMP AL,'A'
    JB VTC_LOWER

    CMP AL,'Z'
    JBE VTC_OK

    JMP VTC_LOWER

VTC_LOWER:

    CMP AL,'a'
    JB VTC_DIGIT

    CMP AL,'z'
    JBE VTC_OK

    JMP VTC_DIGIT

VTC_DIGIT:

    CMP AL,'0'
    JB VTC_SYMBOLS

    CMP AL,'9'
    JBE VTC_OK

    JMP VTC_SYMBOLS

VTC_SYMBOLS:

    CMP AL,','
    JE VTC_OK

    CMP AL,'.'
    JE VTC_OK

    CMP AL,':'
    JE VTC_OK

    MOV AL,00H
    RET

VTC_OK:

    MOV AL,01H
    RET

VALIDATE_TEXT_CHAR ENDP

; Calcula la posicion del cursor dentro del buffer

GET_BUFFER_POSITION PROC NEAR

    PUSH AX
    PUSH BX
    PUSH DX

    XOR AX,AX

    MOV AL,EDITOR_ROW
    SUB AL,EDITOR_TOP

    MOV BL,80
    MUL BL

    XOR BX,BX

    MOV BL,EDITOR_COL
    ADD AX,BX

    LEA DI,TEXT_BUFFER
    ADD DI,AX

    POP DX
    POP BX
    POP AX

    RET

GET_BUFFER_POSITION ENDP

; Avanza el cursor despues de escribir

MOVE_CURSOR_RIGHT PROC NEAR

    CMP EDITOR_COL,EDITOR_RIGHT
    JAE MCR_NEW_LINE

    INC EDITOR_COL
    JMP MCR_UPDATE

MCR_NEW_LINE:

    MOV EDITOR_COL,EDITOR_LEFT

    CMP EDITOR_ROW,EDITOR_BOTTOM
    JB MCR_NEXT_ROW

    JMP MCR_UPDATE

MCR_NEXT_ROW:

    INC EDITOR_ROW

MCR_UPDATE:

    CALL UPDATE_CURSOR

    RET

MOVE_CURSOR_RIGHT ENDP

; Actualiza la posicion del cursor en pantalla

UPDATE_CURSOR PROC NEAR

    PUSH AX
    PUSH BX
    PUSH DX

    MOV AH,02H
    MOV BH,00H
    MOV DH,EDITOR_ROW
    MOV DL,EDITOR_COL

    INT 10H

    POP DX
    POP BX
    POP AX

    RET

UPDATE_CURSOR ENDP

; Guarda el contenido del editor en el archivo

SAVE_FILE PROC NEAR

    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX

    MOV BX,FILE_HANDLE

    MOV AX,4200H

    XOR CX,CX
    XOR DX,DX

    INT 21H

    MOV BX,FILE_HANDLE

    MOV AH,40H
    MOV CX,1840

    LEA DX,TEXT_BUFFER

    INT 21H

    MOV BX,FILE_HANDLE

    MOV AH,3EH

    INT 21H

    MOV FILE_HANDLE,0000H

    POP DX
    POP CX
    POP BX
    POP AX

    RET

SAVE_FILE ENDP

